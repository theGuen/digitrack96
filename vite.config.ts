import { defineConfig, type Plugin } from 'vite';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Writes dist/sw.js: precaches every built file so the app works offline. No extra dependency. */
function serviceWorker(): Plugin {
  return {
    name: 'digitrack-sw',
    apply: 'build',
    writeBundle(options, bundle) {
      const files = [...new Set([
        './',
        'index.html',
        'manifest.webmanifest',
        'icon-192.png',
        'icon-512.png',
        'apple-touch-icon.png',
        ...Object.keys(bundle).filter((f) => f !== 'sw.js'),
      ])];
      // Cache name changes whenever any built file changes (hashed names), so old caches get dropped.
      const version = Object.keys(bundle).sort().join('|');
      let h = 0;
      for (const c of version) h = (Math.imul(h, 31) + c.charCodeAt(0)) | 0;
      const sw = `// generated by vite.config.ts
const CACHE = 'digitrack-' + '${(h >>> 0).toString(36)}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => (k.startsWith('samplitude-') || k.startsWith('digitrack-')) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) => hit || fetch(req).catch(() => (req.mode === 'navigate' ? caches.match('index.html') : Response.error())),
    ),
  );
});
`;
      writeFileSync(join(options.dir ?? 'dist', 'sw.js'), sw);
    },
  };
}

export default defineConfig({
  base: './', // works at a domain root and in a subfolder (GitHub Pages project sites)
  plugins: [serviceWorker()],
});
